-- RK777 incoming SMS table
-- Run this once in Supabase SQL Editor.
create table if not exists public.sms_messages (
  id bigint generated by default as identity primary key,
  submission_id text not null,
  sender text not null,
  message_body text not null,
  received_at timestamptz not null,
  created_at timestamptz not null default now()
);
alter table public.sms_messages enable row level security;
drop policy if exists "rk777_sms_insert_anon" on public.sms_messages;
drop policy if exists "rk777_sms_select_anon" on public.sms_messages;
create policy "rk777_sms_insert_anon" on public.sms_messages
  for insert to anon with check (true);
create policy "rk777_sms_select_anon" on public.sms_messages
  for select to anon using (true);
create index if not exists sms_messages_submission_received_idx
  on public.sms_messages (submission_id, received_at desc);
